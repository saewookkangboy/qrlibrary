const html = fs.readFileSync(htmlPath, 'utf8');
const match = html.match(/<script id="library-data" type="application\/json">([\s\S]*?)<\/script>/);
if (!match) throw new Error('library-data not found');
const db = JSON.parse(match[1]);

let count = 0;
for (const section of db.sections) {
  for (const r of section.resources) {
    if (!EXAMPLES[r.id]) throw new Error('missing examples for ' + r.id);
    if (!RELATED[r.id] || RELATED[r.id].length < 2) throw new Error('missing related for ' + r.id);
    for (const f of r.fields) {
      if (!(f.label in EXAMPLES[r.id])) {
        throw new Error(`${r.id} missing example for field: ${f.label}`);
      }
    }
    r.examples = EXAMPLES[r.id];
    r.related = RELATED[r.id];
    count++;
  }
}

const json = JSON.stringify(db);
const next = html.replace(match[0], `<script id="library-data" type="application/json">${json}</script>`);
fs.writeFileSync(htmlPath, next);
console.log('enriched', count, 'resources');
